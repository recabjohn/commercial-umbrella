"""Crime FRC analysis (Page, Page Fields, Domain sheets; state AL vs countrywide CW) -> markdown + domains json.
usage: py -I crime_frc_analysis.py <frc-data-full dir> <out md> <out domains json>
"""
import csv
import collections
import json
import re
import sys
from pathlib import Path

D, OUT, DOMJ = Path(sys.argv[1]), Path(sys.argv[2]), Path(sys.argv[3])


def rd(tag, name):
    return list(csv.DictReader(open(D / f"{tag}_{name}.csv", encoding="utf-8")))


def clean(s):
    return re.sub(r"<[^>]+>|&nbsp;", "", s).strip()


def domains(tag):
    """Entries sheet: block header = '<Table>,<KeyName|Sequence>,Sequence,Display Value,DataValue'; keyed blocks carry key value in col 2."""
    res, cur = {}, None
    for r in csv.reader(open(D / f"{tag}_entries.csv", encoding="utf-8")):
        r += [""] * (5 - len(r))
        if r[0] in ("Table", "Domain Table"):
            continue
        if "Display Value" in r[2:4]:                                    # header row
            keyed = r[3] == "Display Value"
            cur = {"table": r[0], "key": r[1] if keyed else None}
            res.setdefault(r[0], {"key": cur["key"], "items": []})
            continue
        if cur is None or r[0] != cur["table"]:
            continue
        item = {"k": r[1], "v": r[4], "d": r[3]} if cur["key"] else {"k": None, "v": r[3], "d": r[2]}
        res[r[0]]["items"].append(item)
    return res


data = {}
for tag in ("AL", "CW"):
    data[tag] = dict(page=rd(tag, "page"), fields=rd(tag, "fields"), dom=rd(tag, "domains"), keys=rd(tag, "domainkeys"), ent=domains(tag))

A, C = data["AL"], data["CW"]
GROUPS = [p["Name"] for p in sorted((p for p in A["page"] if p["Parent"] == "Policy" and p["Type"] == "Summary"), key=lambda p: int(p["Sequence"]))]
MINE = {"Policy"} | set(GROUPS) | {g + " Detail" for g in GROUPS}
L = []
w = L.append


def table(head, rows):
    w("| " + " | ".join(head) + " |")
    w("|" + "---|" * len(head))
    for r in rows:
        w("| " + " | ".join(str(c).replace("|", "/") for c in r) + " |")
    w("")


w("# Crime 02 - FRC analysis: Page, Page Fields, Domain Tables (state AL and countrywide CW)")
w("")
w("Source: `FRC-CR-AL-06012022-V01.xlsx` and `FRC-CR-CW-06012022-V01.xlsx` (inside `RC-CR-xx-06012022-V01.zip` of each ERC package). Only the sheets Page, Page Fields, Domain Tables, Domain Table Keys, Domain Table Entries were read; exported with `scripts/frc_sheets_full.py`; this file generated by `scripts/crime_frc_analysis.py` (numbers are counted, not typed).")
w("")
# ---- Page sheet
w("## 1. Page sheet - hierarchy")
for tag in ("AL", "CW"):
    c = collections.Counter(p["Type"] for p in data[tag]["page"])
    w(f"- **{tag}**: {len(data[tag]['page'])} pages = " + ", ".join(f"{k} {v}" for k, v in c.items()) + ".")
roots = [p for p in A["page"] if not p["Parent"]]
w(f"- Root (blank Parent): **{roots[0]['Name']}**, type {roots[0]['Type']}, table {roots[0]['Table']}, occurs {roots[0]['Min Occurs']}..{roots[0]['Max Occurs']}. One root only: {len(roots) == 1}.")
w(f"- Direct non-form children of Policy: {len(GROUPS)} Summary pages (the groups). Direct children that are Forms: {sum(1 for p in A['page'] if p['Parent'] == 'Policy' and p['Type'] == 'Form')} (ignored, as for CU).")
w("")
rows = []
for g in GROUPS:
    s = next(p for p in A["page"] if p["Name"] == g and p["Type"] == "Summary")
    d = next(p for p in A["page"] if p["Name"] == g + " Detail")
    sc = next(p for p in C["page"] if p["Name"] == g and p["Type"] == "Summary")
    rows.append([s["Sequence"], g, s["Table"], f"{s['Min Occurs']}..{s['Max Occurs']}", f"{d['Min Occurs']}..{d['Max Occurs']}", "same" if (s["Condition"], s["Sequence"]) == (sc["Condition"], sc["Sequence"]) else "DIFFERENT"])
table(["Sequence", "Group (Summary page)", "Table", "Group rows", "Detail rows", "AL = CW?"], rows)
w("Every group is **0..1**: one Summary row and one Detail form, no many-row schedule. Detail page is a child of the group Summary page.")
w("")
w("### 1.1 Which groups show: the Condition column")
w("Each group page has a Condition built from two Policy fields, **Monoline Policy Type** or **Package Policy Type** (plus the group already existing on the record):")
for g in GROUPS:
    s = next(p for p in A["page"] if p["Name"] == g and p["Type"] == "Summary")
    vals = sorted(set(re.findall(r"(?:Monoline|Package)PolicyType='([^']+)'", s["Condition"])))
    w(f"- **{g}** shows when the policy type is one of: " + "; ".join(vals))
w("")
nonform_other = [p for p in A["page"] if p["Type"] != "Form" and p["Name"] != "Policy" and p["Name"] not in GROUPS and not any(p["Name"] == g + " Detail" for g in GROUPS)]
w(f"- Other non-form pages (form schedules, e.g. Co-Surety Summary/Detail, Policy Change): {len(nonform_other)}. They hang under Form pages, so they belong to the forms and are out of scope.")
w("")
w("### 1.2 AL vs CW (Page sheet)")
sa, sc_ = {(p["Name"], p["Parent"], p["Type"]) for p in A["page"]}, {(p["Name"], p["Parent"], p["Type"]) for p in C["page"]}
w(f"- Only in AL: {len(sa - sc_)} (all Forms: {all(t == 'Form' for _, _, t in sa - sc_)}); only in CW: {len(sc_ - sa)} (all Forms: {all(t == 'Form' for _, _, t in sc_ - sa)}).")
for n, _, _ in sorted(sa - sc_):
    w(f"  - AL only: {n}")
for n, _, _ in sorted(sc_ - sa):
    w(f"  - CW only: {n}")
nf = lambda s: {x for x in s if x[2] != "Form"}                                                         # noqa: E731
w(f"- Non-form pages (the hierarchy that matters): AL {len(nf(sa))}, CW {len(nf(sc_))}, identical: {nf(sa) == nf(sc_)}.")
w("")
# ---- Page fields
w("## 2. Page Fields sheet")
fa, fc = {tuple(f.values()) for f in A["fields"]}, {tuple(f.values()) for f in C["fields"]}
w(f"- AL {len(A['fields'])} fields, CW {len(C['fields'])} fields; rows only in AL: {len(fa - fc)}, only in CW: {len(fc - fa)} (identical: {fa == fc}).")
cnt = collections.Counter(f["Page"] for f in A["fields"] if f["Page"] in MINE)
w(f"- Fields on the 15 pages we need: {sum(cnt.values())} (Policy {cnt['Policy']}; group Summary pages {sum(cnt[g] for g in GROUPS)}; group Detail pages {sum(cnt[g + ' Detail'] for g in GROUPS)}).")
w("- Field types overall: " + ", ".join(f"{k} {v}" for k, v in collections.Counter(f["Type"] for f in A["fields"]).most_common()) + ".")
w("")
w("### 2.1 Policy page (the 22 fields)")
rows = []
for f in A["fields"]:
    if f["Page"] == "Policy":
        rows.append([f["Sequence"], f["Field"], f["Type"], clean(f["Label"])[:58], f["Quote Required"], f["Default"], f["Domain Table"], f["Condition"][:60] + ("..." if len(f["Condition"]) > 60 else "")])
table(["Seq", "Field", "Type", "Label", "Req", "Default", "List", "Condition"], rows)
w("### 2.2 Group Summary pages (table columns)")
rows = [[g, "; ".join(f"{f['Field']} ({clean(f['Label'])})" for f in A["fields"] if f["Page"] == g)] for g in GROUPS]
table(["Group", "Fields"], rows)
w("### 2.3 Group Detail pages")
rows = []
for g in GROUPS:
    d = [f for f in A["fields"] if f["Page"] == g + " Detail"]
    t = collections.Counter(f["Type"] for f in d)
    inc = sum(1 for f in d if f["Field"].endswith("Included"))
    hdr = sum(1 for f in d if f["Comment"].startswith("Header"))
    cond = sum(1 for f in d if f["Condition"])
    rows.append([g, len(d), ", ".join(f"{k} {v}" for k, v in t.most_common()), inc, hdr, cond, sum(1 for f in d if f["Quote Required"] == "Yes")])
table(["Group", "Fields", "Types", "'...Included' switches", "Header rows", "With Condition", "Required"], rows)
sample = [f for f in A["fields"] if f["Page"] == "Commercial Crime Detail"][:12]
w("Pattern (first rows of Commercial Crime Detail): an **Included** Yes/No switch per coverage, followed by that coverage's Premium, Varying-Deductible flag, Limit and Deductible.")
table(["Seq", "Field", "Type", "Label", "Domain", "Condition"], [[f["Sequence"], f["Field"][:70], f["Type"], clean(f["Label"])[:30], f["Domain Table"], f["Condition"][:40]] for f in sample])
w("### 2.4 Condition patterns on our 15 pages")
pat = collections.Counter()
for f in A["fields"]:
    if f["Page"] in MINE and f["Condition"]:
        pat[re.sub(r"'[^']*'", "'..'", re.sub(r"\.\./\w+", "../X", f["Condition"]))[:90]] += 1
table(["Condition shape", "Fields"], pat.most_common(8))
# ---- domains
w("## 3. Domain Tables, Keys and Entries sheets")
w(f"- {len(A['dom'])} domain tables (CW {len(C['dom'])}); {len(A['keys'])} key rows (CW {len(C['keys'])}); the Entries sheet carries value lists for {sum(1 for v in A['ent'].values() if v['items'])} tables.")
w("- Keyed domain = its list depends on another field (Domain Table Keys sheet). In the Entries sheet a keyed block has the key value in column 2.")
used = collections.defaultdict(list)
for f in A["fields"]:
    if f["Page"] in MINE and f["Domain Table"]:
        used[f["Domain Table"]].append(f["Page"])
rows = []
for d, pgs in sorted(used.items()):
    e = A["ent"].get(d, {"key": None, "items": []})
    rows.append([d, len(pgs), e["key"] or "-", len(e["items"]), ("; ".join(x["v"] for x in e["items"][:3]))[:60]])
table(["List", "Fields using it", "Depends on", "Values", "First values"], rows)
w("### 3.1 Dependency chains between fields (from the Keys sheet and Policy fields)")
w("- Entity Type (Commercial/Government) -> Legal Entity, Major Industry Group, Monoline Policy Type, Package Policy Type, Risk Type.")
w("- Major Industry Group -> Predominant Activity -> Class Description and Class Code.")
w("- Monoline Policy Type -> Monoline Coverage Type; Package Policy Type -> Package Coverage Type.")
w("- Coverage limit and deductible lists depend on the coverage's **Included** switch (key name 'Included').")
w("")
w("### 3.2 Policy-type lists (these decide which groups show)")
for d in ("EntityType", "MonolinePolicyType", "PackagePolicyType"):
    e = A["ent"][d]
    by = collections.defaultdict(list)
    for x in e["items"]:
        by[x["k"] or "-"].append(x["v"])
    for k, v in by.items():
        w(f"- {d}{' / ' + e['key'] + '=' + k if e['key'] else ''}: " + "; ".join(v))
w("")
ca, cc = {d: [(x["k"], x["v"]) for x in v["items"]] for d, v in A["ent"].items()}, {d: [(x["k"], x["v"]) for x in v["items"]] for d, v in C["ent"].items()}
w(f"### 3.3 AL vs CW (domains): domain table rows identical: {A['dom'] == C['dom']}; key rows identical: {A['keys'] == C['keys']}; entry values identical (ignoring Status): {ca == cc}.")
w("")
OUT.write_text("\n".join(L), encoding="utf-8")
DOMJ.write_text(json.dumps({d: v for d, v in A["ent"].items()}, indent=0), encoding="utf-8")
print("written", OUT, len(L), "lines")
